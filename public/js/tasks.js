/* ---------- допоміжне форматування ---------- */
const sg = (n) => (n < 0 ? `- ${Math.abs(n)}` : `+ ${n}`);
const kx = (k, v = 'x') => (k === 1 ? v : k === -1 ? `-${v}` : `${k}${v}`);
const poly2 = (a, b, c) => `${kx(a, 'x^2')}${b ? ` ${sg(b)}x` : ''}${c ? ` ${sg(c)}` : ''}`;
const frac = (p, q) => (q === 1 ? `${p}` : `\\frac{${p}}{${q}}`);

